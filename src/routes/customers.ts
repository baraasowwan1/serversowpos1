import { Router, Response } from "express";
import { Customer } from "../models/index";
import { authMiddleware, AuthRequest, scopeToStore } from "../middleware/auth";
const router = Router();
router.use(authMiddleware);
router.get("/", async (req: AuthRequest, res: Response) => { res.json(await Customer.find(scopeToStore(req)).sort({ createdAt: -1 })); });
router.post("/", async (req: AuthRequest, res: Response) => { res.status(201).json(await Customer.create({ ...req.body, ...scopeToStore(req) })); });
router.put("/:id", async (req: AuthRequest, res: Response) => { res.json(await Customer.findOneAndUpdate({ _id: req.params["id"], ...scopeToStore(req) }, req.body, { new: true })); });
router.delete("/:id", async (req: AuthRequest, res: Response) => { await Customer.findOneAndDelete({ _id: req.params["id"], ...scopeToStore(req) }); res.json({ ok: true }); });
export default router;
